import { appendFile, readFile } from "node:fs/promises";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import process from "node:process";
import { fileURLToPath } from "node:url";

const execFileAsync = promisify(execFile);
const DEFAULT_COMMIT_MESSAGE = "chore: sync marketplace source metadata";

function packagesBySlug(catalog) {
  return new Map((catalog.packages ?? []).map((entry) => [entry.slug, entry]));
}

function sameEntry(left, right) {
  return JSON.stringify(left) === JSON.stringify(right);
}

function compareMarketplacePackages(before, after) {
  const beforeBySlug = packagesBySlug(before);
  const afterBySlug = packagesBySlug(after);
  const versionChanges = [];
  const metadataChanges = [];
  const added = [];
  const removed = [];

  for (const entry of after.packages ?? []) {
    const previous = beforeBySlug.get(entry.slug);
    if (!previous) {
      added.push({ slug: entry.slug, name: entry.name, version: entry.version });
      continue;
    }
    if (previous.version !== entry.version) {
      versionChanges.push({
        slug: entry.slug,
        name: entry.name,
        beforeVersion: previous.version,
        afterVersion: entry.version
      });
      continue;
    }
    if (!sameEntry(previous, entry)) {
      metadataChanges.push({ slug: entry.slug, name: entry.name, version: entry.version });
    }
  }

  for (const entry of before.packages ?? []) {
    if (!afterBySlug.has(entry.slug)) {
      removed.push({ slug: entry.slug, name: entry.name, version: entry.version });
    }
  }

  return { versionChanges, metadataChanges, added, removed };
}

function formatCommitMessage(changes) {
  const hasOnlyVersionChanges =
    changes.versionChanges.length > 0 &&
    changes.metadataChanges.length === 0 &&
    changes.added.length === 0 &&
    changes.removed.length === 0;

  if (hasOnlyVersionChanges && changes.versionChanges.length === 1) {
    const change = changes.versionChanges[0];
    return `chore: bump ${change.slug} to ${change.afterVersion}`;
  }

  if (hasOnlyVersionChanges && changes.versionChanges.length === 2) {
    const [first, second] = changes.versionChanges;
    const message = `chore: bump ${first.slug} to ${first.afterVersion} and ${second.slug} to ${second.afterVersion}`;
    if (message.length <= 100) {
      return message;
    }
  }

  if (changes.versionChanges.length > 0) {
    return `chore: bump ${changes.versionChanges.length} marketplace packages`;
  }
  if (changes.added.length === 1 && changes.removed.length === 0 && changes.metadataChanges.length === 0) {
    const entry = changes.added[0];
    return `chore: add ${entry.slug} ${entry.version}`;
  }
  if (changes.added.length > 0 || changes.removed.length > 0) {
    return "chore: sync marketplace package set";
  }
  if (changes.metadataChanges.length > 0) {
    return "chore: sync marketplace metadata";
  }
  return DEFAULT_COMMIT_MESSAGE;
}

function bulletList(items, formatter) {
  return items.map((item) => `- ${formatter(item)}`);
}

function formatMarkdownSummary(changes, changedFiles) {
  const lines = [
    "## Summary",
    "",
    "- Syncs marketplace entries from `jxpeng98/skills`.",
    "- Syncs `qiongli` and `qiongli-next` from Qiongli release channels.",
    "- Runs `npm run validate` before opening this PR.",
    "",
    "## Version Updates",
    ""
  ];

  if (changes.versionChanges.length > 0) {
    lines.push(
      ...bulletList(
        changes.versionChanges,
        (change) => `${change.slug}: \`${change.beforeVersion}\` -> \`${change.afterVersion}\``
      )
    );
  } else {
    lines.push("- No package version changes detected.");
  }

  if (changes.added.length > 0) {
    lines.push("", "## Added Packages", "");
    lines.push(...bulletList(changes.added, (entry) => `${entry.slug}: \`${entry.version}\``));
  }

  if (changes.removed.length > 0) {
    lines.push("", "## Removed Packages", "");
    lines.push(...bulletList(changes.removed, (entry) => `${entry.slug}: \`${entry.version}\``));
  }

  if (changes.metadataChanges.length > 0) {
    lines.push("", "## Metadata Changes", "");
    lines.push(...bulletList(changes.metadataChanges, (entry) => `${entry.slug}: \`${entry.version}\``));
  }

  if (changedFiles.length > 0) {
    lines.push("", "## Changed Files", "");
    lines.push(...changedFiles.map((file) => `- \`${file}\``));
  }

  lines.push("", "## Source", "", "Generated by `.github/workflows/sync-marketplace-sources.yml`.");
  return `${lines.join("\n")}\n`;
}

export function summarizeMarketplaceSync({ before, after, changedFiles = [] }) {
  const changes = compareMarketplacePackages(before, after);
  const commitMessage = formatCommitMessage(changes);
  const markdown = formatMarkdownSummary(changes, changedFiles);
  return {
    changes,
    commitMessage,
    prTitle: commitMessage,
    prBody: markdown,
    stepSummary: markdown
  };
}

async function readJson(filePath) {
  return JSON.parse(await readFile(filePath, "utf8"));
}

async function readBaseMarketplace() {
  const { stdout } = await execFileAsync("git", ["show", "HEAD:marketplace.json"]);
  return JSON.parse(stdout);
}

async function readChangedFiles() {
  const { stdout } = await execFileAsync("git", [
    "diff",
    "--name-only",
    "--",
    "marketplace.json",
    ".agents/plugins/marketplace.json",
    ".claude-plugin/marketplace.json",
    ".antigravity/catalog.json",
    ".hermes/marketplace.json"
  ]);
  return stdout
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean);
}

async function appendGithubOutput(outputs) {
  if (!process.env.GITHUB_OUTPUT) {
    return;
  }
  const blocks = Object.entries(outputs).map(([name, value]) => {
    const delimiter = `SKILLSPLACE_${name.toUpperCase()}_${process.pid}`;
    return `${name}<<${delimiter}\n${value}\n${delimiter}\n`;
  });
  await appendFile(process.env.GITHUB_OUTPUT, blocks.join(""));
}

async function appendGithubStepSummary(markdown) {
  if (!process.env.GITHUB_STEP_SUMMARY) {
    return;
  }
  await appendFile(process.env.GITHUB_STEP_SUMMARY, markdown);
}

async function main() {
  const before = await readBaseMarketplace();
  const after = await readJson("marketplace.json");
  const changedFiles = await readChangedFiles();
  const summary = summarizeMarketplaceSync({ before, after, changedFiles });

  await appendGithubOutput({
    commit_message: summary.commitMessage,
    pr_title: summary.prTitle,
    pr_body: summary.prBody
  });
  await appendGithubStepSummary(summary.stepSummary);
  console.log(summary.stepSummary);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await main();
}
